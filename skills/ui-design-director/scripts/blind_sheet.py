#!/usr/bin/env python3
"""블라인드 판정 그림 — 우리 화면과 실제 사이트 화면을 같은 크기로 자르고, 로고 자리를 가리고, 순서를 섞는다.

    python blind_sheet.py <out-dir> 우리=<ours.jpg> 이름=<ref.jpg> 이름=<ref.jpg> ... [--seed N] [--height 1800]

결과: <out-dir>/site-1.jpg … 와 key.json(답 — 판정하는 에이전트에게 보여 주지 않는다), prompt.txt(판정 요청 글).
판정은 이 대화를 모르는 새 에이전트가 한다. 「우리」를 AI로 70% 넘게 확신하면 통과가 아니다(page-design.md § Composition first).
같은 모델이 「괜찮아요?」에 답하면 너그럽다 — 섞어 놓고 고르게 해야 엄격해진다.
"""
from __future__ import annotations

import json
import random
import sys
from pathlib import Path

from PIL import Image, ImageDraw

WIDTH = 1280          # 비교 폭(넓은 화면)
OUT_WIDTH = 960       # 판정 그림 폭
LOGO_BOX = (0, 0, 420, 90)  # 로고가 있을 왼쪽 위 — 회색으로 가린다
LOGO_GREY = "#888888"
PROMPT = """You are a strict senior web designer judging {n} website homepages (desktop, top part, logos greyed out). Some are real running sites made by professional agencies; one or more may have been generated by an AI coding assistant — or none. You don't know which. Read only these images: {files}. Do not open key.json.
For each site (answer in Korean): 1) 판정 「실제 운영 사이트」 or 「AI·템플릿으로 만든 것」 with confidence %; 2) 디자인 완성도 1–10 (10 = agency work); 3) 2–4 concrete visual tells. Then rank them, and for every site judged AI-made list the top 3 changes that would raise it toward the best real site. Be blunt. Judge the design, not cookie banners or half-loaded images."""


def main() -> int:
    args = sys.argv[1:]
    if len(args) < 3:
        print(__doc__)
        return 1
    out = Path(args[0])
    seed = int(args[args.index("--seed") + 1]) if "--seed" in args else random.randrange(1 << 16)
    height = int(args[args.index("--height") + 1]) if "--height" in args else 1800
    items = [a.split("=", 1) for a in args[1:] if "=" in a and not a.startswith("--")]
    out.mkdir(parents=True, exist_ok=True)
    random.Random(seed).shuffle(items)
    key = {}
    for n, (name, path) in enumerate(items, 1):
        im = Image.open(path).convert("RGB")
        scale = WIDTH / im.width
        im = im.resize((WIDTH, round(im.height * scale))).crop((0, 0, WIDTH, height))
        ImageDraw.Draw(im).rectangle(LOGO_BOX, fill=LOGO_GREY)
        im.resize((OUT_WIDTH, round(height * OUT_WIDTH / WIDTH))).save(out / f"site-{n}.jpg", quality=85)
        key[n] = name
    (out / "key.json").write_text(json.dumps({"seed": seed, "key": key}, ensure_ascii=False, indent=1), encoding="utf-8")
    files = ", ".join(str(out / f"site-{n}.jpg") for n in key)
    (out / "prompt.txt").write_text(PROMPT.format(n=len(key), files=files), encoding="utf-8")
    print(f"ok {len(key)}장 · 답은 {out / 'key.json'} · 판정 요청 글은 {out / 'prompt.txt'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
